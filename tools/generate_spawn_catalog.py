"""Generate the Rust browser index from the curated and community JSON catalogs."""

from __future__ import annotations

import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
CURATED = ROOT / "assets/catalog/entities.json"
COMMUNITY = ROOT / "assets/catalog/community-candidates.json"
OUTPUT = ROOT / "src/devtools/overlay/spawn_menu_catalog.rs"
SPAWN_OUTPUT = ROOT / "src/api/scripts/spawn_catalog.rs"


def rust_string(value: str) -> str:
    if not value.isascii():
        raise ValueError(f"Catalog strings must be ASCII for the Rust source generator: {value!r}")
    return json.dumps(value)


def tile_status(entry: dict[str, object]) -> str:
    readiness = entry["spawn_readiness"]
    if readiness == "verified":
        return "Stable"
    asset_key = entry.get("asset_key")
    has_spawn_route = (
        isinstance(asset_key, str)
        and bool(asset_key.strip())
        and not asset_key.startswith(("/", "\\"))
        and ".." not in asset_key.split("/")
        and "\\" not in asset_key
    )
    return "Experimental" if has_spawn_route else "NoSpawnPath"


def main() -> None:
    curated = json.loads(CURATED.read_text(encoding="utf-8"))["entries"]
    community = json.loads(COMMUNITY.read_text(encoding="utf-8"))["entries"]

    entries: list[dict[str, object]] = []
    seen_asset_keys: set[str] = set()
    for entry in [*curated, *community]:
        asset_key = entry.get("asset_key", "")
        if not isinstance(asset_key, str):
            asset_key = ""
        if asset_key and asset_key in seen_asset_keys:
            continue
        if asset_key:
            seen_asset_keys.add(asset_key)
        category = entry["category"]
        status = tile_status(entry)
        entries.append(
            {
                "catalog_id": entry["id"],
                "name": entry["name"],
                "category": " / ".join(category),
                "section": category[0],
                "asset_key": asset_key,
                "status": status,
                # Green and yellow are actionable. Red means there is no known
                # safe-relative asset path for the generic entity spawn call.
                "spawnable": status != "NoSpawnPath",
            }
        )

    lines = [
        "// Generated by tools/generate_spawn_catalog.py from assets/catalog/*.json.",
        "// Do not edit this file directly; update the source catalog and regenerate.",
        "use super::spawn_menu::{CatalogEntry, CatalogTileStatus};",
        "",
        "pub(super) static CATALOG: &[CatalogEntry] = &[",
    ]
    for entry in entries:
        lines.extend(
            [
                "    CatalogEntry {",
                f"        catalog_id: {rust_string(entry['catalog_id'])},",
                f"        name: {rust_string(entry['name'])},",
                f"        category: {rust_string(entry['category'])},",
                f"        section: {rust_string(entry['section'])},",
                f"        asset_key: {rust_string(entry['asset_key'])},",
                f"        status: CatalogTileStatus::{entry['status']},",
                f"        spawnable: {str(entry['spawnable']).lower()},",
                "    },",
            ]
        )
    lines.append("];\n")
    OUTPUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")

    spawnable = [entry for entry in entries if entry["spawnable"]]
    spawn_lines = [
        "// Generated from assets/catalog/*.json by tools/generate_spawn_catalog.py.",
        "// Green and yellow catalog entries are spawn attempts; entries without a usable path are excluded.",
        "static SPAWNABLE: &[(&str, &str)] = &[",
    ]
    for entry in spawnable:
        spawn_lines.append(
            f"    ({rust_string(entry['catalog_id'])}, {rust_string(entry['asset_key'])}),"
        )
    spawn_lines.extend(
        [
            "];",
            "",
            "pub(crate) fn asset_key(catalog_id: &str) -> Option<&'static str> {",
            "    SPAWNABLE.iter().find_map(|(id, key)| (*id == catalog_id).then_some(*key))",
            "}",
            "",
            "pub(crate) fn is_spawnable(catalog_id: &str) -> bool {",
            "    asset_key(catalog_id).is_some()",
            "}",
            "",
        ]
    )
    SPAWN_OUTPUT.write_text("\n".join(spawn_lines), encoding="utf-8", newline="\n")
    counts = {
        status: sum(entry["status"] == status for entry in entries)
        for status in ("Stable", "Experimental", "NoSpawnPath")
    }
    print(
        f"Generated {len(entries)} unique browser entries ({len(spawnable)} spawnable): "
        f"{counts['Stable']} stable, {counts['Experimental']} experimental, "
        f"{counts['NoSpawnPath']} without a spawn path "
        f"at {OUTPUT.relative_to(ROOT)} and {SPAWN_OUTPUT.relative_to(ROOT)}"
    )


if __name__ == "__main__":
    main()
