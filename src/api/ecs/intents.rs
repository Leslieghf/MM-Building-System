//! Owned requests for game effects and their validation/completion records.
//!
//! Systems create intents here rather than invoking the game. Constructors
//! validate portable values and assign host-local request IDs; the game
//! runtime bounds and queues them, then the native adapter resolves the current
//! target and reports an outcome. Queue acceptance does not imply that the
//! game applied the effect.
use crate::api::ecs::config::{MAX_SPAWN_ASSET_KEY_BYTES, NEXT_INTENT_ID};
use crate::api::game::abi::types::Matrix4x4;
use bevy_ecs::prelude::*;
use std::sync::atomic::Ordering;

#[derive(Component, Debug, Clone, Copy, PartialEq)]
/// Requested velocity for the current player vehicle.
pub struct SetPlayerVehicleVelocity(
    #[doc = "Requested X, Y, and Z velocity in game units per second."] pub [f32; 3],
);

#[derive(Component, Debug, Clone, Copy, PartialEq, Eq)]
/// Marker that resolves a velocity effect against the occupied vehicle at consumption time.
pub struct TargetCurrentPlayerVehicle;

#[derive(Component, Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
/// Host-local identifier for a typed game effect.
pub struct IntentId(#[doc = "Monotonic identifier generated by this host process."] pub u64);

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
/// Result of validating and applying a vehicle effect.
pub enum IntentResult {
    /// The native setter accepted the requested value.
    Applied,
    /// One or more components were invalid or outside the supported range.
    InvalidValue,
    /// No current player vehicle was available.
    NoCurrentVehicle,
    /// The native setter could not be resolved for this build.
    SetterUnavailable,
    /// The game callback failed its exclusive-access gate.
    CallbackNotExclusive,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
/// Completion event for a vehicle effect.
pub struct IntentOutcome {
    /// Identifier matching the submitted intent.
    pub intent_id: u64,
    /// Validation/application result.
    pub result: IntentResult,
}

#[derive(Component, Debug, Clone, Copy, PartialEq, Eq)]
/// ECS wrapper for one completed effect outcome.
pub struct IntentOutcomeRecord(#[doc = "The copied velocity effect result."] pub IntentOutcome);

/// Session-local identifier for one requested game spawn. It is not a game
/// spawn ID and must never be passed to the native SDK as one.
#[derive(Component, Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct SpawnRequestId(#[doc = "Host-local request ID; not a native game spawn ID."] pub u64);

/// An owned exported entity key, without the game's `.ee` suffix.
///
/// Construction validates only the key's syntax. It does not prove that the
/// executable contains the entity or that native dispatch will succeed.
///
/// See [`spawn_entity_intent`] for constructing a queued ECS request.
#[derive(Component, Debug, Clone, PartialEq, Eq)]
pub struct SpawnAssetKey(String);

impl SpawnAssetKey {
    /// Validate and own an exported-entity key.
    ///
    /// # Errors
    ///
    /// Returns [`SpawnRequestError::InvalidAssetKey`] when the key is empty,
    /// too long, non-ASCII, outside `editor/entities/`, or contains an invalid
    /// path segment.
    pub fn parse(value: impl Into<String>) -> Result<Self, SpawnRequestError> {
        let value = value.into();
        let valid = !value.is_empty()
            && value.len() <= MAX_SPAWN_ASSET_KEY_BYTES
            && value.is_ascii()
            && value.bytes().all(|byte| {
                byte.is_ascii_lowercase() || byte.is_ascii_digit() || b"/_-".contains(&byte)
            })
            && value.starts_with("editor/entities/")
            && !value.ends_with('/')
            && !value
                .split('/')
                .any(|segment| segment.is_empty() || segment == "." || segment == "..");
        if valid {
            Ok(Self(value))
        } else {
            Err(SpawnRequestError::InvalidAssetKey)
        }
    }

    /// Return the validated normalized entity key.
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

/// Owned row-major placement matrix copied from the game's pointer-free matrix
/// value. Native calls remain outside this ECS component.
#[derive(Component, Debug, Clone, Copy, PartialEq)]
pub struct SpawnTransform {
    /// Finite row-major transform copied into the request.
    pub matrix: Matrix4x4,
}

impl SpawnTransform {
    /// Accept a finite row-major transform for a spawn request.
    ///
    /// # Errors
    ///
    /// Returns [`SpawnRequestError::InvalidTransform`] if any matrix element is
    /// non-finite.
    pub fn new(matrix: Matrix4x4) -> Result<Self, SpawnRequestError> {
        if matrix
            .values
            .iter()
            .flatten()
            .all(|value| value.is_finite())
        {
            Ok(Self { matrix })
        } else {
            Err(SpawnRequestError::InvalidTransform)
        }
    }
}

/// Lifecycle vocabulary for spawn intents. The native adapter currently
/// reports submission only; the later observer must confirm spawned state.
#[derive(Component, Debug, Clone, Copy, PartialEq, Eq)]
pub enum SpawnLifecycle {
    /// Validated and waiting for dispatch.
    Queued,
    /// Rejected before native dispatch.
    Rejected,
    /// Currently being sent to the native spawn entry point.
    Dispatching,
    /// Submitted; awaiting a separate observation of spawned state.
    PendingObservation,
    /// Spawned state was observed by a later observer.
    Spawned,
    /// A despawn operation has been requested.
    DespawnRequested,
    /// Despawned state was observed by a later observer.
    Despawned,
    /// Native dispatch or later observation failed.
    Failed,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
/// Reason a spawn request could not be constructed or queued.
pub enum SpawnRequestError {
    /// Entity key does not use supported syntax.
    InvalidAssetKey,
    /// One or more transform components are non-finite.
    InvalidTransform,
    /// Bounded spawn request transport has no free slot.
    QueueFull,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
/// Native dispatch outcome for a validated spawn request.
pub enum SpawnRequestResult {
    /// The callback safety gate rejected the request.
    CallbackNotExclusive,
    /// The native spawn function was not available.
    NativeSymbolUnavailable,
    /// The native spawn identifier could not be allocated.
    SpawnIdUnavailable,
    /// Request validation failed before native dispatch.
    InvalidRequest,
    /// The native call was submitted; spawned state still needs observation.
    NativeCallSubmitted,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
/// Owned report for one spawn request.
pub struct SpawnOutcome {
    /// Host request identifier.
    pub request_id: u64,
    /// Submission result.
    pub result: SpawnRequestResult,
    /// Native return value, when a call was made.
    pub native_return: Option<usize>,
}

#[derive(Component, Debug, Clone, Copy, PartialEq, Eq)]
/// ECS wrapper for one spawn request outcome.
pub struct SpawnOutcomeRecord(#[doc = "The copied spawn dispatch result."] pub SpawnOutcome);

/// Build the ECS components for a validated spawn request.
///
/// # Errors
///
/// Returns [`SpawnRequestError::InvalidAssetKey`] or
/// [`SpawnRequestError::InvalidTransform`] when either input fails validation.
/// The returned bundle must still be inserted into the game world; dispatch
/// outcome is reported separately through [`SpawnOutcome`].
pub fn spawn_entity_intent(
    asset_key: impl Into<String>,
    matrix: Matrix4x4,
) -> Result<impl Bundle, SpawnRequestError> {
    let asset_key = SpawnAssetKey::parse(asset_key)?;
    let transform = SpawnTransform::new(matrix)?;
    let request_id = SpawnRequestId(NEXT_INTENT_ID.fetch_add(1, Ordering::Relaxed));
    Ok((request_id, asset_key, transform, SpawnLifecycle::Queued))
}

/// Build an effect for the vehicle occupied when the adapter consumes it.
///
/// This constructor does not validate velocity. The adapter validates finite
/// components and the supported speed range before applying the request.
pub fn player_vehicle_velocity_intent(velocity: [f32; 3]) -> impl Bundle {
    (
        TargetCurrentPlayerVehicle,
        IntentId(
            crate::api::ecs::config::NEXT_INTENT_ID
                .fetch_add(1, std::sync::atomic::Ordering::Relaxed),
        ),
        SetPlayerVehicleVelocity(velocity),
    )
}
